"""Sinh bảng T1 và T3 cho mục VI-A của report (P5.1a), để không phải chép số tay vào LaTeX.

Chủ sở hữu: TV1.

  - T1: số nút Minimax và Alpha-Beta duyệt từ bàn 3×3 trống, theo từng chế độ sắp xếp nước.
    Số nút được đo lại mỗi lần chạy (Minimax mất vài giây); chế độ `random` lấy trung bình,
    nhỏ nhất và lớn nhất trên các seed 0..`--seeds`-1.
  - T3: đọc `experiments/results/verify_never_lose_summary.csv` (do
    `python -m experiments.verify_never_lose` sinh ra) và chuyển thành bảng LaTeX.
  - F1/F2: in ra terminal tỷ lệ thắng theo (c, iteration) từ `p31b_3x3.csv`, `p31b_9x9.csv` để
    đối chiếu với phần chữ của report. c được đổi về thang [0, 1] của đề: c_đề = c_code / 2.

Chạy từ gốc repo:

    python -m experiments.report_tables

Đầu ra: `report/tables/T1.tex`, `report/tables/T3.tex`.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import statistics
import sys
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path

from src.agents.alphabeta import AlphaBetaAgent
from src.agents.base import Agent, Budget
from src.agents.minimax import MinimaxAgent
from src.games.tictactoe import TicTacToe

RESULTS = Path("experiments/results")
TABLES = Path("report/tables")
HEADER = "% Generated by experiments/report_tables.py -- do not edit by hand.\n"
THIN_SPACE = r"\,"


def fmt(n: float) -> str:
    """Số nguyên với dấu cách mảnh LaTeX giữa các nhóm ba chữ số."""
    return f"{n:,.0f}".replace(",", THIN_SPACE)


def count_nodes(agent: Agent) -> int:
    """Số nút `agent` duyệt khi chọn nước từ bàn 3×3 trống, không giới hạn độ sâu."""
    agent.select_move(TicTacToe(), Budget())
    return int(agent.last_stats["nodes"])


def t1_rows(seeds: int) -> list[tuple[str, str, str]]:
    """Các dòng (phương pháp, số nút, mức giảm so với Minimax) của bảng T1."""
    minimax_nodes = count_nodes(MinimaxAgent())

    def reduction(nodes: float) -> str:
        return f"{100.0 * (1.0 - nodes / minimax_nodes):.1f}\\%"

    rows = [("Minimax", fmt(minimax_nodes), "--")]
    for ordering in ("natural", "heuristic"):
        nodes = count_nodes(AlphaBetaAgent(ordering=ordering))
        rows.append((f"Alpha-beta, {ordering} order", fmt(nodes), reduction(nodes)))

    random_nodes = [count_nodes(AlphaBetaAgent(ordering="random", seed=s)) for s in range(seeds)]
    mean = statistics.mean(random_nodes)
    spread = f"{fmt(min(random_nodes))}--{fmt(max(random_nodes))}"
    rows.append(
        (f"Alpha-beta, random order ({seeds} seeds)", f"{fmt(mean)} ({spread})", reduction(mean))
    )
    return rows


def render_t1(rows: Sequence[tuple[str, str, str]]) -> str:
    body = "".join(f"{name} & {nodes} & {red} \\\\\n" for name, nodes, red in rows)
    return (
        HEADER
        + "\\begin{tabular}{lrr}\n\\toprule\n"
        + "Search & Nodes visited & Reduction \\\\\n\\midrule\n"
        + body
        + "\\bottomrule\n\\end{tabular}\n"
    )


def render_t3(summary_csv: Path) -> str:
    body = []
    with summary_csv.open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            body.append(
                f"{fmt(int(r['iterations']))} & {r['seeds_never_lose']}/{r['seeds']} & "
                f"{fmt(int(r['tree_losses']))} & {r['minimax_draws']}/{r['minimax_games']} \\\\\n"
            )
    return (
        HEADER
        + "\\begin{tabular}{rrrr}\n\\toprule\n"
        + "Iterations & Seeds never losing & Losing lines & Draws vs.\\ Minimax \\\\\n"
        + "\\midrule\n"
        + "".join(body)
        + "\\bottomrule\n\\end{tabular}\n"
    )


def win_rates(csv_path: Path) -> dict[tuple[float, int], tuple[int, int, int, int]]:
    """(c_đề, iteration) -> (số ván, thắng, hòa, thua) của MCTS (bên A) trong file P3.1b."""
    agg: dict[tuple[float, int], list[int]] = defaultdict(lambda: [0, 0, 0, 0])
    with csv_path.open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            params = json.loads(r["a_params"])
            cell = agg[(params["c"] / 2.0, int(params["budget"]["iterations"]))]
            cell[0] += 1
            cell[1] += r["winner"] == "a"
            cell[2] += r["winner"] == "draw"
            cell[3] += r["winner"] == "b"
    return {k: (v[0], v[1], v[2], v[3]) for k, v in agg.items()}


def two_proportion_z(w1: int, n1: int, w2: int, n2: int) -> tuple[float, float]:
    """Kiểm định z hai tỷ lệ (phương sai gộp), trả về (z, p hai phía)."""
    pooled = (w1 + w2) / (n1 + n2)
    se = math.sqrt(pooled * (1.0 - pooled) * (1.0 / n1 + 1.0 / n2))
    if se == 0.0:
        return 0.0, 1.0
    z = (w1 / n1 - w2 / n2) / se
    return z, math.erfc(abs(z) / math.sqrt(2.0))


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Sinh bảng T1, T3 cho report (P5.1a)")
    parser.add_argument("--seeds", type=int, default=20, help="số seed cho thứ tự random")
    parser.add_argument("--out-dir", type=Path, default=TABLES)
    args = parser.parse_args(argv)
    if args.seeds < 1:
        parser.error("--seeds phải >= 1")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    rows = t1_rows(args.seeds)
    (args.out_dir / "T1.tex").write_text(render_t1(rows), encoding="utf-8")
    t3 = render_t3(RESULTS / "verify_never_lose_summary.csv")
    (args.out_dir / "T3.tex").write_text(t3, encoding="utf-8")

    print("T1:")
    for row in rows:
        print("  " + " | ".join(row))
    for name in ("p31b_3x3", "p31b_9x9"):
        rates = win_rates(RESULTS / f"{name}.csv")
        print(f"{name} (c trên thang [0, 1]: số ván / thắng / hòa / thua, tỷ lệ thắng):")
        for (c, it), (n, w, d, lose) in sorted(rates.items()):
            print(f"  c={c:.1f} I={it:5d}: {n}/{w}/{d}/{lose}  {w / n:.3f}")
        low_c, high_c = min(c for c, _ in rates), max(c for c, _ in rates)
        for it in sorted({i for _, i in rates}):
            n1, w1, *_ = rates[(low_c, it)]
            n2, w2, *_ = rates[(high_c, it)]
            z, p = two_proportion_z(w1, n1, w2, n2)
            print(f"  tỷ lệ thắng c={low_c} vs c={high_c}, I={it}: z={z:.2f}, p={p:.4f}")
    print(f"Đã ghi {args.out_dir / 'T1.tex'} và {args.out_dir / 'T3.tex'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
