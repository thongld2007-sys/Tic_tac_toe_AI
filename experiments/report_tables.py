"""Sinh các bảng LaTeX của report từ code và CSV kết quả, để không phải chép số tay.

Chủ sở hữu: TV1.

  - T1: số nút Minimax và Alpha-Beta duyệt từ bàn 3×3 trống, theo từng chế độ sắp xếp nước.
    Số nút được đo lại mỗi lần chạy (Minimax mất vài giây); chế độ `random` lấy trung bình,
    nhỏ nhất và lớn nhất trên các seed 0..`--seeds`-1.
  - T3: đọc `experiments/results/verify_never_lose_summary.csv` (do
    `python -m experiments.verify_never_lose` sinh ra) và chuyển thành bảng LaTeX.
  - F1/F2: in ra terminal tỷ lệ thắng theo (c, iteration) từ `p31b_3x3.csv`, `p31b_9x9.csv` để
    đối chiếu với phần chữ của report. c được đổi về thang [0, 1] của đề: c_đề = c_code / 2.

Chạy từ gốc repo:

    python -m experiments.report_tables

  - T2, T4–T7, B2B3, B4: đọc các CSV tổng hợp trong `experiments/results/` (T2 cần
    `p5_t2_ab_ablation.csv` từ `configs/p5_t2_ab_ablation.yaml`); thiếu CSV thì bỏ qua bảng đó.

Đầu ra: `report/tables/*.tex`.
"""

